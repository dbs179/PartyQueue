// Which descriptor energies clash with each DJ mood. Unlisted moods
// (all/custom/unknown) accept everything.
const DESCRIPTOR_ENERGY_EXCLUDES = Object.freeze({
  party: ["low"],
  heavy: ["low"],
  rap: ["low"],
  chill: ["high"],
  kids: ["high"],
});

/** Descriptors that make sense for a mood ("any" always qualifies). */
export function filterDescriptorsForMood(mood, descriptors = DJ_SET_DESCRIPTORS) {
  const excluded = DESCRIPTOR_ENERGY_EXCLUDES[String(mood || "")] || [];
  if (!excluded.length) return [...descriptors];
  return descriptors.filter((entry) => !excluded.includes(entry.energy));
}

export function filterIntrosByContext(context, intros = DJ_SHARED_INTROS) {
  if (!DJ_INTRO_CONTEXTS.includes(context)) return [];
  return intros.filter((entry) => entry.contexts.includes(context));
}

export function filterAsidesByFamilySafety(
  familySafe,
  asides = DJ_BOOTH_ASIDES
) {
  return asides.filter((entry) => entry.familySafe === familySafe);
}
