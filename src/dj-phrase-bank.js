export function filterIntrosByContext(context, intros = DJ_SHARED_INTROS) {
  if (!DJ_INTRO_CONTEXTS.includes(context)) return [];
  return intros.filter((entry) => entry.contexts.includes(context));
}

export function filterAsidesByFamilySafety(
  familySafe,
  asides = DJ_BOOTH_ASIDES
) {
  return asides.filter((entry) => entry.familySafe === familySafe);
}
